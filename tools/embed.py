#!/usr/bin/env python3
"""embed.py FILE OUT.h NAME: writes OUT.h with a char array holding the contents of FILE (to embed it in the binary)."""
import sys
data = open(sys.argv[1], "rb").read()
name = sys.argv[3]
with open(sys.argv[2], "w") as o:
    o.write("// generated by tools/embed.py: do not edit\n#pragma once\nstatic const char %s[] = {\n" % name)
    for i in range(0, len(data), 24):
        o.write(",".join(str(b - 256 if b > 127 else b) for b in data[i:i + 24]) + ",\n")		# signed char: a UTF-8 byte above 127 cannot be an unsigned constant (narrowing)
    o.write("0};\nstatic const unsigned long %s_size = %d;\n" % (name, len(data)))
