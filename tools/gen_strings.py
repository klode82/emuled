#!/usr/bin/env python3
# Generates core/Strings.h: all the English IDS_ texts of emule.rc (except those already in ServerStrings.h/SearchStrings.h).
import re,sys
sys.path.insert(0,__import__('os').path.dirname(__import__('os').path.abspath(__file__)))
from upstream import SRCHYBRID
rc=open(__import__('os').path.join(SRCHYBRID,'emule.rc'),encoding='cp1252',errors='replace').read().replace('\r','')
have=set()
for f in ('core/ServerStrings.h','core/search/SearchStrings.h'):
    have|=set(re.findall(r'#define (IDS_\w+)',open(f,encoding='utf-8').read()))
out=['// LINUX: generated by tools/gen_strings.py from srchybrid/emule.rc (English texts). Do not edit by hand.','#pragma once']
seen=set()
lines=rc.split('\n')
i=0
pat=re.compile(r'^\s+(IDS_\w+)\s*(".*)?$')
while i<len(lines):
    m=pat.match(lines[i])
    i+=1
    if not m: continue
    name,txt=m.groups()
    if txt is None:
        if i<len(lines) and lines[i].lstrip().startswith('"'):
            txt=lines[i].strip(); i+=1
        else: continue
    # continuation: next line starting with " (spaces)
    while i<len(lines) and lines[i].lstrip().startswith('"') and not pat.match(lines[i]):
        txt+=lines[i].strip(); i+=1
    txt=txt.rstrip()
    if name in have or name in seen: continue
    seen.add(name)
    # rc: "" inside = quotes; \r \n \t stay C escapes
    body=re.sub(r'"\s*"','',txt) if False else txt
    inner=txt[1:txt.rfind('"')]
    inner=inner.replace('""','\\"').replace('&&','&')
    import re as _re
    inner=_re.sub(r'(%[-+ #0-9.*]*)I64([udixX])',r'\1ll\2',inner); inner=_re.sub(r'(%[-+ #0-9.*]*)(?:hs|ls)\b',r'\1s',inner)
    inner=re.sub(r'\\"\\"\s*','\\"',inner) if False else inner
    out.append('#define %s "%s"'%(name,inner))
open('core/Strings.h','w',encoding='utf-8').write('\n'.join(out)+'\n')
print(len(seen))
